function isYearLike(s) {
    const n = parseInt(s, 10);
    if (isNaN(n)) return false;
    // On considère comme "année" tout nombre entre -5000 et aujourd'hui
    return n >= -5000 && n <= 2100;
}

function isNumber(s) {
    return !isNaN(parseInt(s, 10)) && /^-?\d+$/.test(s);
}

function isRoman(s) {
    if (!s || s.length === 0) return false;
    // Regex pour chiffres romains. On évite les lettres isolées trop communes (comme 'i' ou 'v' seul)
    // sauf si elles sont en majuscules ou dans un contexte de chiffres.
    // Pour le jeu, on va être assez large mais demander au moins un caractère romain valide.
    const romanRegex = /^(?=[MDCLXVI])M{0,4}(CM|CD|D?C{0,3})(XC|XL|L?X{0,3})(IX|IV|V?I{0,3})$/i;
    if (s.length === 1 && !/^[IVXLCDM]$/i.test(s)) return false;
    return romanRegex.test(s);
}

export async function checkWord(guess, target) {
    if (!guess || !target) return false;

    // Cas particulier : Les Années / Dates
    if (isYearLike(guess) && isYearLike(target)) {
        return 'synonym';
    }

    // Cas particulier : Chiffres Romains (si les deux en sont)
    if (isRoman(guess) && isRoman(target)) {
        return 'synonym';
    }

    // Cas particulier : Nombres génériques (si l'un est le synonyme de l'autre)
    if (isNumber(guess) && isNumber(target)) {
        // Optionnel : On pourrait limiter aux nombres proches ou juste "tout nombre est synonyme de tout nombre"
        // pour aider à repérer les stats/données chiffrées
        return 'synonym';
    }

    for (const group of SYNONYM_GROUPS) {
        if (group.includes(guess) && group.includes(target)) {
            return 'synonym';
        }
    }

    return false;
}

export function checkSynonymMatch(target, guesses) {
    // Nombres / Dates dynamiques : on cherche le plus proche
    if (isNumber(target)) {
        let best = null;
        let minDiff = Infinity;
        const targetVal = parseInt(target, 10);

        for (const g of guesses) {
            if (isNumber(g)) {
                const diff = Math.abs(targetVal - parseInt(g, 10));
                if (diff < minDiff) {
                    minDiff = diff;
                    best = g;
                }
            }
        }
        if (best !== null) return best;
    }

    // Chiffres romains dynamiques
    if (isRoman(target)) {
        for (const g of guesses) {
            if (isRoman(g)) return g;
        }
    }

    for (const group of SYNONYM_GROUPS) {
        if (group.includes(target)) {
            for (const guess of guesses) {
                if (group.includes(guess)) {
                    return guess;
                }
            }
        }
    }
    return null;
}

export function renderSynonymHint(span, guess) {
    if (span.classList.contains('revealed') || span.classList.contains('found')) return;
    
    const target = span.dataset.clean;
    const oldHint = span.getAttribute('data-hint');

    // Si on a déjà un indice, on vérifie si le nouveau est "meilleur" (plus proche pour les nombres)
    if (oldHint && isNumber(target) && isNumber(guess) && isNumber(oldHint)) {
        const targetVal = parseInt(target, 10);
        const newVal = parseInt(guess, 10);
        const oldVal = parseInt(oldHint, 10);
        
        // Si l'ancien indice était plus proche (ou égal) du résultat, on le garde
        if (Math.abs(targetVal - oldVal) <= Math.abs(targetVal - newVal)) {
            return;
        }
    }

    // On retire close-match s'il y est, car synonym-hint est prioritaire
    span.classList.remove('close-match');
    span.classList.add('synonym-hint');
    span.setAttribute('data-hint', guess);
}

export function getSynonyms(word) {
    let syns = [];
    for (const group of SYNONYM_GROUPS) {
        if (group.includes(word)) {
            syns = syns.concat(group.filter(w => w !== word));
        }
    }
    return syns;
}
